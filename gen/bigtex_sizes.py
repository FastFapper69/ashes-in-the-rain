# Painted sizes of the street and room drawings whose import is capped at 2048 px (see bigtex.gd).
# Run after adding a drawing; also sets process/size_limit=2048 in its .import.
import glob, json, re
from PIL import Image
d = {}
for f in glob.glob('art/street/*.png') + glob.glob('art/rooms/*.png'):
    w, h = Image.open(f).size
    if w > 2048:
        d['res://' + f] = [w, h]
        p = f + '.import'
        s = open(p).read()
        open(p, 'w').write(re.sub(r'process/size_limit=\d+', 'process/size_limit=2048', s))
with open('big_sizes.gd', 'w') as f:
    f.write('extends RefCounted\n## Generated by gen/bigtex_sizes.py: painted sizes of the drawings capped at 2048 px.\n\nconst SIZES := {\n')
    for k in sorted(d):
        f.write('\t"%s": Vector2i(%d, %d),\n' % (k, d[k][0], d[k][1]))
    f.write('}\n')
print(len(d), 'capped drawings')
