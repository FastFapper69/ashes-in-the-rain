# Which drawings are imported as Basis Universal (compress/mode=4): on the phone they stay GPU-compressed
# (ASTC, 1 byte a pixel instead of 4) and need no WebP decode when a street drawing streams in.
# WebGL refuses a compressed texture whose size is not a multiple of 4 (S3TC/BPTC on a desktop browser),
# so only drawings whose IMPORTED size is a multiple of 4 both ways become Basis:
#  - drawings loaded through BigTex.get_tex (street/room drawings with their _lit/_solid layers, comic
#    panels): their import is capped a few pixels smaller, to a size in multiples of 4, and big_sizes.gd
#    keeps their painted size, which BigTex reports (UVs follow it), so no pixel position moves;
#  - every other drawing only if its own size already is; the rest stay lossy WebP (mode=1).
# Never Basis: anything read back with get_image() (LowRes, Paper, hats), normal maps (_n).
# Run after adding art; it also rewrites big_sizes.gd (gen/bigtex_sizes.py does the same).
import glob, re
from PIL import Image

def cap_for(w, h):
    """The largest size_limit (<= 2048, below the long side) giving an imported size in multiples of 4."""
    long, short = max(w, h), min(w, h)
    top = min(2048, long - 1)
    for L in range(top - top % 4, top - 400, -4):
        if (short * L // long) % 4 == 0:
            return L
    return 0

def wrapped(f):
    """Loaded through BigTex.get_tex: free to be imported at a slightly different size."""
    n = f.split('/')[-1]
    return (f.startswith(('art/street/', 'art/rooms/')) and '_neon' not in n) or f.startswith('art/cut/')

def candidates():
    files = glob.glob('art/street/*.png') + glob.glob('art/rooms/*.png') + glob.glob('art/fore/*.png') + glob.glob('art/cut/*.jpg')
    files += ['art/bg/%s.png' % n for n in ['far', 'mid', 'fore', 'moon', 'wall2', 'wall2_lit']]
    files += ['art/props/%s.png' % n for n in ['scaffold', 'station_stairs', 'subway_car', 'subway_car_lit']]
    return [f for f in files if not f.endswith('_n.png')]

big = {}
basis = webp = 0
for f in candidates():
    p = f + '.import'
    s = open(p).read()
    w, h = Image.open(f).size
    if wrapped(f) and (w > 2048 or w % 4 or h % 4):
        L = cap_for(w, h)
        big['res://' + f] = (w, h)
        s = re.sub(r'process/size_limit=\d+', 'process/size_limit=%d' % L, s)
        iw, ih = (L, h * L // w) if w >= h else (w * L // h, L)
    else:
        lim = int(re.search(r'process/size_limit=(\d+)', s).group(1))
        iw, ih = (w, h)
        if lim and max(w, h) > lim:
            iw, ih = (lim, h * lim // w) if w >= h else (w * lim // h, lim)
    ok = iw % 4 == 0 and ih % 4 == 0
    s = re.sub(r'compress/mode=\d', 'compress/mode=%d' % (4 if ok else 1), s)
    open(p, 'w').write(s)
    basis += ok
    webp += not ok
with open('big_sizes.gd', 'w') as f:
    f.write('extends RefCounted\n## Generated by gen/basis_imports.py / gen/bigtex_sizes.py: painted sizes of the drawings whose import is capped (<= 2048 px).\n\nconst SIZES := {\n')
    for k in sorted(big):
        f.write('\t"%s": Vector2i(%d, %d),\n' % (k, big[k][0], big[k][1]))
    f.write('}\n')
print(basis, 'Basis,', webp, 'left as WebP,', len(big), 'capped drawings')
